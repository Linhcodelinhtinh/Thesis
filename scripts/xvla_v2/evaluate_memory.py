def comparison(reference, protocol, roster, seed, source_hashes, environments, contract, condition="F1"):
    """Historical parity is an audit result, never an unconditional score label."""
    differences = []
    if reference is None:
        return dict(status="UNVERIFIED_NO_REFERENCE", differences=["No SmolVLA run manifest supplied"])
    args = reference["arguments"]
    if reference.get("status") != "complete":
        differences.append("reference run is not complete")
    if args.get("policy_seed") != seed or args.get("decision_mode") is not None:
        differences.append("policy seed or decision schedule differs")
    if reference.get("protocol") != protocol:
        differences.append("canonical task protocol differs")
    identity = lambda rows: {(r["task"], r["state_idx"], r["source_demo"], r["initial_state_sha256"],
                             r["instruction"]) for r in rows}
    if identity(reference["roster"]) != identity(roster):
        differences.append("task/state/instruction roster differs")
    treatment = reference.get("treatments", {}).get(condition, {})
    if condition == "F1" and (treatment.get("memory_source") != contract["writer"]
            or treatment.get("projection") != contract["writer_config"]["projection"]
            or treatment.get("projection_strategy") != contract["writer_config"]["strategy"]):
        differences.append("F1 writer/projection differs")
    if condition != "F1" and treatment.get("memory_source") != "none":
        differences.append("missing or different instruction-only reference treatment")
    shared = ("src/simulator/libero_mem_env.py", "src/simulator/libero_mem_loader.py",
              "src/evaluation/libero_mem_rollout.py", "src/evaluation/libero_mem_metrics.py")
    for name in (*shared, *contract["writer_code_sha256"]):
        expected_hash = reference.get("source_sha256", {}).get(name)
        if expected_hash is not None and expected_hash != source_hashes.get(name):
            differences.append("shared source differs: " + name)
    if reference.get("reference_writer_code_sha256") != contract["writer_code_sha256"]:
        differences.append("reference and training writer provenance differ")
    # F0 is instruction-only, so its paired SmolVLA F0 run does not depend on
    # the detector runtime even when the historical combined run loaded one
    # for its separate F1 condition. F1 memory-on must match the detector.
    components = ("simulator", "detector") if condition == "F1" else ("simulator",)
    for component in components:
        before = reference.get("environments", {}).get(component, {})
        after = environments.get(component, {})
        if before.get("python") != after.get("python") or before.get("packages") != after.get("packages"):
            differences.append(component + " runtime differs")
    return dict(status="DESCRIPTIVE_ONLY" if differences else "MATCHED_TASK_PROTOCOL_CROSS_BACKBONE",
                differences=differences,
                mandatory_model_differences=["SmolVLA delta OSC / XVLA absolute OSC",
                    "native chunk SmolVLA 50 / XVLA 30; both execute prefix 10",
                    "official image preprocessing, tokenizer and proprio differ by backbone"],
                interpretation="Cross-backbone outcome comparison; not a causal memory effect or official LIBERO score")


def merge_references(paths):
    if not paths:
        return None
    references = [json.loads(path.read_text(encoding="utf-8")) for path in paths]
    first = dict(references[0])
    roster, seen = [], set()
    reference_writer_code = None
    for path, item in zip(paths, references):
        if item.get("status") != "complete":
            raise ValueError("Reference batch is incomplete")
        for key in ("protocol", "source_sha256", "environments", "treatments"):
            if item.get(key) != first.get(key):
                raise ValueError("Reference batches disagree on " + key)
        for key in ("policy_seed", "decision_mode"):
            if item["arguments"].get(key) != first["arguments"].get(key):
                raise ValueError("Reference batches disagree on " + key)
        adapter_path = path.parent / "adapter_manifest_F1.json"
        if not adapter_path.is_file():
            raise FileNotFoundError("Missing F1 adapter manifest in SmolVLA batch: " + str(path.parent))
        adapter_manifest = json.loads(adapter_path.read_text(encoding="utf-8"))
        writer_code = adapter_manifest["memory_provenance"][0]["writer_code_sha256"]
        if reference_writer_code is not None and writer_code != reference_writer_code:
            raise ValueError("Reference batches use different writer source hashes")
        reference_writer_code = writer_code
        for row in item["roster"]:
            key = (row["task"], row["state_idx"])
            if key in seen:
                raise ValueError("Duplicate task/state in reference batches")
            seen.add(key)
            roster.append(row)
    first["roster"] = roster
    first["reference_writer_code_sha256"] = reference_writer_code
    return first


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--adapter-dir", type=Path, required=True)
    p.add_argument("--arm", choices=("F0", "F1"), default="F1")
    p.add_argument("--memory", choices=("on", "off"), default="on")
    p.add_argument("--checkpoint", type=Path, default=ROOT / "resources/checkpoints/x_vla_libero")
    p.add_argument("--shards-manifest", type=Path, default=ROOT / "experiments/training/relations-author-split-v2/shards/manifest.json")
    p.add_argument("--writer-source-root", type=Path, help="Attested memory_source.py snapshot; no working tree replacement")
    p.add_argument("--split-lock", type=Path, default=DEFAULT_AUTHOR_MEM_LOCK)
    p.add_argument("--split", choices=("seen", "unseen"), default="unseen")
    p.add_argument("--states", default="all")
    p.add_argument("--tasks", choices=("T1", "T3"), nargs="+", default=["T1", "T3"])
    p.add_argument("--policy-seed", type=int, default=42)
    p.add_argument("--sim-python", required=True)
    p.add_argument("--detector-python")
    p.add_argument("--inference-python", type=Path, required=True)
    p.add_argument("--detector-model", type=Path, default=ROOT / "resources/models/grounding-dino-tiny")
    p.add_argument("--smolvla-reference", type=Path, nargs="+", help="Completed SmolVLA E2 run manifests, one or all batches")
    p.add_argument("--require-matched-reference", action="store_true")
    p.add_argument("--output-dir", type=Path, required=True)
    p.add_argument("--preflight-only", action="store_true")
    p.add_argument("--runtime-check", action="store_true", help="Two real actions on one selected state per task; no score")
    p.add_argument("--decision-mode", choices=("text", "shadow", "event", "periodic"))
    p.add_argument("--decision-exposure", choices=("projected", "snapshot"), default="projected")
    p.add_argument("--halt", choices=("off", *HALT_MODES), default="off",
                   help="Memory-gated halt treatment (separate condition; requires --memory on)")
    p.add_argument("--halt-confirm-queries", type=int, default=1)
    p.add_argument("--halt-retract-m", type=float, default=0.0)
    p.add_argument("--halt-no-support-check", action="store_true",
                   help="Ablation: halt on count + open gripper without the confirmed on-plate relation")
    p.add_argument("--halt-allow-closed-gripper", action="store_true",
                   help="Ablation: also halt (and open the gripper) when the count is reached while grasping")
    p.add_argument("--halt-source", choices=COUNT_SOURCES, default="writer",
                   help="Return count the halt reads: the prompt writer (default), a V4 shadow writer, V4 + proprio cue "
                        "fused per cycle, or the simulator's confirmed cycles (privileged upper bound)")
    p.add_argument("--freeze-detector-after-halt", action="store_true",
                   help="Hold mode only: stop detector/shadow work once the halt latches (actions unchanged)")
    p.add_argument("--port", type=int, default=8010)
    p.add_argument("--timeout", type=int, default=600)
    a = p.parse_args(argv)
    if not 1 <= a.port <= 65535 or a.timeout < 1 or not 0 <= a.policy_seed < 2**32:
        p.error("Invalid port, timeout or policy seed")
    if a.memory == "on" and not a.detector_python:
        p.error("--memory on requires isolated --detector-python")
    if a.halt != "off" and a.memory != "on":
        p.error("--halt reads the memory writer and requires --memory on")
    if a.halt != "off":
        # Validate once before any process starts; target_cycles is set per task.
        HaltConfig(1, mode=a.halt, confirm_queries=a.halt_confirm_queries, retract_m=a.halt_retract_m,
                   require_on_support=not a.halt_no_support_check,
                   require_gripper_open=not a.halt_allow_closed_gripper)
    if a.halt == "off" and (a.halt_source != "writer" or a.freeze_detector_after_halt):
        p.error("--halt-source and --freeze-detector-after-halt need --halt")
    if a.freeze_detector_after_halt and a.halt != "hold":
        p.error("--freeze-detector-after-halt is only valid with --halt hold (gripper_lock keeps querying the policy)")
    if a.halt_source == "oracle" and not a.halt_no_support_check:
        a.halt_no_support_check = True    # the simulator's confirmed cycle already encodes the plate predicate
    if a.decision_mode and (a.split != "seen" or a.arm != "F1" or a.memory != "on" or a.halt != "off"):
        p.error("Decision modes require F1 memory-on on seen states and no halt treatment")
    decision_protocol = load_decision_protocol() if a.decision_mode else None
    decision_execution = (execution_treatment(decision_protocol, a.decision_mode, a.decision_exposure)
                          if decision_protocol else None)
    output = a.output_dir.absolute()
    output.mkdir(parents=True, exist_ok=False)
    manifest = dict(classification="CUSTOM_V2_XVLA_MEM", comparability="NON-COMPARABLE_OFFICIAL_PAPER",
                    status="preflight", arguments=vars(a))
    write_json(output / "run_manifest.json", manifest)
    try:
        spec = yaml.safe_load((ROOT / "resources/manifests/models/x_vla_libero.yaml").read_text())
        verify_checkout(ROOT / "external/X-VLA", spec["code_revision"])
        verify_files(a.checkpoint, spec["sha256"])
        export = verify_adapter(a.adapter_dir, spec)
        verify_files(a.adapter_dir, export["files"])
        if export["arm"] != a.arm or export["steps"] != 5000:
            raise ValueError("Wrong adapter arm or training step")
        shards = json.loads(a.shards_manifest.read_text(encoding="utf-8"))
        if (sha256_file(a.shards_manifest) != json.loads((a.adapter_dir / "build_receipt.json").read_text())["source_manifest_sha256"]
                or shards["split_lock_sha256"] != export["split_lock_sha256"]
                or shards["memory_source"] != export["memory_source"]):
            raise ValueError("Training shards provenance differs from XVLA export")
        protocol, lock, roster = evaluation_roster(a.split_lock, a.split, a.tasks, a.states)
        if decision_protocol:
            if (protocol["protocol_id"] != decision_protocol["parent_protocol_id"]
                    or protocol["rollout"]["execution_horizon"] != decision_protocol["parent_execution_horizon"]
                    or protocol["rollout"]["horizon_policy_actions"] != decision_protocol["policy_actions"]
                    or lock["lock_sha256"] != decision_protocol["split_lock_sha256"]):
                raise ValueError("Decision protocol differs from its locked parent")
            manifest.update(decision_protocol=decision_protocol,
                            decision_protocol_sha256=source_digest(DEFAULT_DECISION_PROTOCOL))
        if lock["lock_sha256"] != export["split_lock_sha256"]:
            raise ValueError("Evaluation split differs from training lock")
        contract = shards["memory_provenance"][0]
        for item in shards["memory_provenance"]:
            if any(item[k] != contract[k] for k in ("writer", "writer_config", "writer_code_sha256", "detector")):
                raise ValueError("Training tasks have different memory contracts")
        if contract["writer"] != "rgb_relations_v1" or contract["writer_config"] != dict(
                projection="relation_text_v1", strategy="relevant", max_total_tokens=48):
            raise ValueError("Unsupported V2 memory contract")
        # No writer override: drift must fail before a policy can receive a prompt.
        if a.memory == "on":
            mismatches = []
            for name, digest in contract["writer_code_sha256"].items():
                try:
                    verify_files(a.writer_source_root or ROOT, {name: digest})
                except ValueError:
                    mismatches.append(dict(path=name, expected=digest, actual=sha256_file((a.writer_source_root or ROOT) / name)))
            manifest["writer_hash_mismatches"] = mismatches
            write_json(output / "run_manifest.json", manifest)
            if mismatches:
                raise ValueError("Writer source differs from training shards: " + str(mismatches))
            import importlib
            for name, digest in contract["writer_code_sha256"].items():
                if name.startswith("src/") and name.endswith(".py"):
                    module = importlib.import_module(name[:-3].replace("/", "."))
                    verify_files(Path(module.__file__).parent, {Path(module.__file__).name: digest})
            verify_files(a.detector_model, contract["detector"]["files"])
        environments = {"orchestrator": runtime_identity(sys.executable),
                        "simulator": runtime_identity(a.sim_python),
                        "inference": runtime_identity(a.inference_python)}
        if a.memory == "on":
            environments["detector"] = runtime_identity(a.detector_python)
        inference = environments["inference"]
        if (not inference["python"].startswith("3.10.")
                or inference["packages"]["transformers"] != "4.51.3"
                or inference["packages"]["peft"] != "0.17.1"):
            raise ValueError("XVLA requires Python 3.10, Transformers 4.51.3, PEFT 0.17.1")
        identities = [(v["platform"], v["prefix"]) for v in environments.values()]
        if len(identities) != len(set(identities)):
            raise ValueError("Orchestrator, simulator, inference and detector require isolated environments")
        sim = environments["simulator"]
        if sim["python"] != "3.8.13" or any(sim["packages"][k] != protocol["runtime"][k]
                for k in ("robosuite", "bddl", "mujoco", "numpy", "robomimic")):
            raise ValueError("Simulator differs from pinned Mem runtime")
        code = code_identity(output)
        if a.writer_source_root:
            archive = output / "loaded_memory_source"
            archive.mkdir()
            import shutil
            for name in contract["writer_code_sha256"]:
                target = archive / name
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(a.writer_source_root / name, target)
                code["source_sha256"][name] = sha256_file(target)
            runner_name = "src/evaluation/libero_mem_rollout.py"
            runner_target = archive / runner_name
            runner_target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(a.writer_source_root / runner_name, runner_target)
            code["source_sha256"][runner_name] = sha256_file(runner_target)
            manifest["memory_source_receipt"] = json.loads((a.writer_source_root / "memory_source_receipt.json").read_text())
        reference = merge_references(a.smolvla_reference)
        reference_condition = a.arm
        audit = comparison(reference, protocol, roster, a.policy_seed, code["source_sha256"], environments, contract,
                           reference_condition)
        if a.arm == "F0" and a.memory == "on":
            audit["status"] = "DESCRIPTIVE_ONLY"
            audit["differences"].append("F0 memory-on is an intervention on instruction-only training")
        if a.halt != "off":
            audit["status"] = "DESCRIPTIVE_ONLY"
            audit["differences"].append("memory-gated halt execution treatment (" + a.halt + ")")
        manifest.update(code, model=spec, adapter_export=export, protocol=protocol, roster=roster,
            protocol_sha256=source_digest(DEFAULT_PROTOCOL), split_lock_sha256=lock["lock_sha256"],
            memory_contract=contract, environments=environments, comparison=audit,
            weight_arm=a.arm, memory_exposure=a.memory,
            inference_intervention=("memory_on_instruction_trained_F0" if a.arm == "F0" and a.memory == "on" else None),
            execution_treatment=(None if a.halt == "off" else dict(
                name="memory_halt", mode=a.halt, confirm_queries=a.halt_confirm_queries,
                retract_m=a.halt_retract_m, require_on_support=not a.halt_no_support_check,
                require_gripper_open=not a.halt_allow_closed_gripper,
                count_source=a.halt_source, freeze_detector_after_halt=a.freeze_detector_after_halt,
                source_sha256=sha256_file(ROOT / "src/evaluation/memory_halt.py"),
                shadow_source_sha256={name: sha256_file(ROOT / name) for name in (
                    "src/evaluation/halt_sources.py", "src/memory/cycle_fusion.py", "src/memory/proprio_cycle_cue.py",
                    "configs/memory/proprio_cycle_cue_v1.json", "src/memory/relation_cycle_writer_v4.py",
                    "configs/memory/relation_plate_prior_v1.json")}
                if a.halt_source in ("v4", "fused") else None)),
            shards_manifest_sha256=sha256_file(a.shards_manifest),
            reference_manifest_sha256={str(path): sha256_file(path) for path in (a.smolvla_reference or [])},
            execution=dict(control_delta=False, action_chunk=30, execution_horizon=10,
                           policy_actions=1000, warmup_delta_steps=20,
                           inference_seed_reset="server_restart_per_episode",
                           inference_port_schedule="base_plus_episode_index"))
        if decision_execution:
            manifest["decision_execution"] = dict(mode=decision_execution.mode,
                exposure=decision_execution.exposure, arm=decision_execution.arm)
        write_json(output / "run_manifest.json", manifest)
        if a.require_matched_reference and audit["status"] != "MATCHED_TASK_PROTOCOL_CROSS_BACKBONE":
            raise ValueError("SmolVLA comparison gate: " + str(audit))
        if a.preflight_only:
            manifest["status"] = "preflight_passed_no_rollout"
            write_json(output / "run_manifest.json", manifest)
            return
        # XVLAProcessor declares BartTokenizerFast explicitly. AutoTokenizer
        # cannot resolve the custom XVLAConfig as a tokenizer config and would
        # prompt for remote model code before failing, so load the author's
        # tokenizer class directly from the same pinned checkpoint files.
        from transformers import BartTokenizerFast
        from scripts.evaluate_mem_adapter import check_runtime_episode
        xvla_tokenizer = BartTokenizerFast.from_pretrained(str(a.checkpoint), local_files_only=True)
        prompt_tokenizer = load_prompt_tokenizer(ROOT / "experiments/training/assets_mem_adapter_v1/backbone")
        suite = load_suite_source(ROOT / "external/libero-mem")
        rows, halt_rows = [], []
        with ExitStack() as resources:
            detector = None
            if a.memory == "on":
                launcher = detector_launcher(a.detector_python, output)
                detector = ProcessRelationDetector(launcher, a.detector_model, device="cuda", timeout_seconds=a.timeout)
                resources.callback(detector.close)
                if detector.provenance != contract["detector"]:
                    raise ValueError("Loaded detector provenance differs from training")
            episode_index = 0
            for task in a.tasks:
                factory, renderer = relation_pipeline(suite, task, detector, "libero_raw", prompt_tokenizer)
                if a.halt != "off" and a.halt_source in ("v4", "fused"):
                    factory = shadow_factory(factory, ProprioCueConfig.load())
                env = ProcessXVLAMemEnv(task, split_lock=a.split_lock, split=a.split,
                                       python_executable=a.sim_python, timeout_seconds=a.timeout)
                try:
                    task_rows = [r for r in roster if r["task"] == task]
                    if a.runtime_check:
                        task_rows = task_rows[:1]
                    for row in task_rows:
                        episode_port = a.port + episode_index
                        if episode_port > 65535:
                            raise ValueError("Episode-specific inference port exceeds 65535")
                        episode_index += 1
                        runner_condition = "F1" if a.memory == "on" else "F0" if a.arm == "F0" else "F1-off"
                        halt_suffix = "" if a.halt == "off" else (f"-halt-{a.halt}" + ("" if a.halt_source == "writer" else f"-{a.halt_source}"))
                        report_condition = f"{a.arm}-mem-{a.memory}{halt_suffix}"
                        ep_id = f"{task}_{a.arm}_mem-{a.memory}{halt_suffix}_{a.split}_state{row['state_idx']}"
                        metadata = dict(row, episode_id=ep_id, condition=report_condition, weight_arm=a.arm,
                                        memory=a.memory, policy_seed=a.policy_seed)
                        if decision_execution:
                            metadata["decision_arm"] = decision_execution.arm
                        server_dir = output / "servers" / ep_id
                        server_dir.mkdir(parents=True)
                        recorder = EpisodeRecorder(output / "episodes" / ep_id, metadata, True, fps=20)
                        policy = XVLAMemPolicy(f"http://127.0.0.1:{episode_port}/act", env, xvla_tokenizer, export, a.timeout)
                        if a.halt != "off":
                            halt_config = HaltConfig(env.target_cycles, mode=a.halt,
                                confirm_queries=a.halt_confirm_queries, retract_m=a.halt_retract_m,
                                require_on_support=not a.halt_no_support_check,
                                require_gripper_open=not a.halt_allow_closed_gripper)
                            current_pose, make_hold = xvla_hold_chunk_factory(env, XVLAMemPolicy.chunk_size)
                            policy = MemoryHaltPolicy(policy, halt_config, current_pose, make_hold, observer=recorder,
                                count_source=a.halt_source, freeze_writer=a.freeze_detector_after_halt,
                                oracle_count=(lambda env=env: env.last_info["eval_result"].confirmed_cycles)
                                if a.halt_source == "oracle" else None)
                        try:
                            with start_server(a.inference_python.absolute(), ROOT / "external/X-VLA", a.checkpoint.absolute(),
                                    server_dir, episode_port, a.timeout, adapter=a.adapter_dir.absolute(), seed=a.policy_seed):
                                if a.runtime_check:
                                    check_runtime_episode(env, policy, renderer,
                                        factory if a.memory == "on" else None, recorder, row, runner_condition)
                                else:
                                    runner = LiberoMemRolloutRunner(env, policy, runner_condition, renderer=renderer,
                                        writer_factory=factory if a.memory == "on" else None, observer=recorder,
                                        stream_memory_trace=True, execution_treatment=decision_execution)
                                    result = runner.run_episode(ep_id, row["instruction"], row["state_idx"])
                            if not a.runtime_check:
                                np.savez_compressed(recorder.directory / "xvla_raw_chunks.npz", raw=np.stack(policy.raw_chunks))
                                if a.halt != "off":
                                    write_json(recorder.directory / "memory_halt.json", policy.summary())
                                    if getattr(factory, "created", None):
                                        write_json(recorder.directory / "shadow_halt.json", factory.created[-1].summary())
                                recorder.finish(result=result)
                        except BaseException as exc:
                            recorder.finish(error=exc)
                            raise
                        if not a.runtime_check:
                            summary = {k: metadata[k] for k in ("episode_id", "task", "condition", "split", "state_idx", "source_demo", "initial_state_sha256")}
                            summary.update(success=result.success, scr=result.scr, overshot=result.overshot,
                                           steps=result.total_steps, policy_ms=result.avg_latency_ms, wall_time_s=result.total_wall_time_s)
                            if a.halt != "off":
                                # report() writes a fixed CSV schema; halt fields go to their own file.
                                halt_rows.append(dict(episode_id=ep_id, task=task, state_idx=row["state_idx"],
                                    halted=policy.halted, halt_step=policy.halt_step, success=result.success,
                                    scr=result.scr, overshot=result.overshot, steps=result.total_steps))
                                write_json(output / "halt_summary.json", halt_rows)
                            rows.append(summary)
                            report(output, rows, len(roster), "running")
                finally:
                    env.close()
        if a.runtime_check:
            manifest.update(status="runtime_checked", completed_episodes=0,
                            completed_runtime_checks=len(a.tasks), runtime_actions_per_check=3,
                            memory_instruction_verified=(a.memory == "on"), score_generated=False)
            (output / "report.md").write_text(
                "# XVLA runtime diagnostic\n\nReal model, detector, writer, simulator IPC and three actions passed per selected task. "
                "For memory-on, the third query carried a writer-generated memory fact. No score generated.\n",
                encoding="utf-8")
        else:
            manifest.update(status="complete", completed_episodes=len(rows))
            report(output, rows, len(roster), "complete")
            with (output / "report.md").open("a", encoding="utf-8") as stream:
                stream.write("\nXVLA comparison audit: " + json.dumps(audit) + "\n")
        write_json(output / "run_manifest.json", manifest)
    except BaseException as exc:
        manifest.update(status="failed", error=str(exc))
        write_json(output / "run_manifest.json", manifest)
        raise


